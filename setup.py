#!/usr/bin/env python3
"""
AI Resume Pilot - Interactive Onboarding Setup Script
Run this script to configure candidate settings, anti-hallucination ground truth,
and Overleaf sync preferences.
"""

import sys
import os
import shutil

def prompt(question, default=None):
    if default:
        res = input(f"{question} [{default}]: ").strip()
        return res if res else default
    else:
        while True:
            res = input(f"{question}: ").strip()
            if res:
                return res
            print("  This field cannot be empty.")

def main():
    print("=" * 70)
    print(" 🎯 AI RESUME PILOT - INTERACTIVE SETUP WIZARD")
    print("=" * 70)
    print("This wizard will help you configure your automated resume tailor.\n")

    # 1. Candidate Info
    first_name = prompt("First Name", "Alex")
    last_name = prompt("Last Name", "Taylor")
    target_role = prompt("Target Title / Role", "Data Engineer | Distributed ETL & Cloud Platforms")
    email = prompt("Email Address", f"{first_name.lower()}.{last_name.lower()}@example.com")
    phone = prompt("Phone Number", "+44 7123 456789")
    location = prompt("Location", "London, UK")
    linkedin = prompt("LinkedIn URL", f"https://linkedin.com/in/{first_name.lower()}-{last_name.lower()}")
    github = prompt("GitHub / Portfolio URL", f"https://github.com/{first_name.lower()}{last_name.lower()}")

    # 2. Work Auth & Location
    print("\n--- Work Authorization & Preferences ---")
    work_auth = prompt("Work Authorization Status", "Full UK work authorisation — no sponsorship required")
    availability = prompt("Availability", "Available immediately for permanent and contract roles")
    location_pref = prompt("Location / Hybrid Preference", f"{location} — open to hybrid and remote roles nationally")

    # 3. Overleaf
    print("\n--- Overleaf Integration (Optional) ---")
    use_overleaf = prompt("Do you want to enable Overleaf Git push? (y/n)", "n").lower().startswith("y")
    overleaf_url = ""
    if use_overleaf:
        overleaf_url = prompt("Overleaf Git Remote URL (e.g. https://git.overleaf.com/PROJECT_ID)")

    # 4. Starting Template
    print("\n--- Base Template Selection ---")
    print("1) Data Engineering / Data Science (Apache Spark, Kafka, SQL, Python, Snowflake, Airflow)")
    print("2) Software Engineering (Backend, Microservices, APIs, Cloud)")
    print("3) Microsoft 365 / SharePoint Developer")
    choice = prompt("Choose starting template (1-3)", "1")

    template_map = {
        "1": "examples/data-engineer/CV_Base_DataEngineer.tex",
        "2": "examples/software-engineer/CV_Base_SWE.tex",
        "3": "examples/sharepoint-m365/CV_Base_SharePoint.tex"
    }
    chosen_template = template_map.get(choice, template_map["1"])

    # 5. Write config.yaml
    cv_prefix = f"{first_name}_{last_name}_CV"
    config_content = f"""# ==============================================================================
# AI Resume Pilot Configuration
# Generated by setup.py
# ==============================================================================

candidate:
  first_name: "{first_name}"
  last_name: "{last_name}"
  title: "{target_role}"
  email: "{email}"
  phone: "{phone}"
  location: "{location}"
  website: ""
  linkedin: "{linkedin}"
  github: "{github}"

work_authorization:
  right_to_work: "{work_auth}"
  availability: "{availability}"
  location_preference: "{location_pref}"

naming_conventions:
  cv_prefix: "{cv_prefix}"
  cover_letter_prefix: "CoverLetter"

overleaf_sync:
  enabled: {"true" if use_overleaf else "false"}
  remote_name: "overleaf"
  branch: "main"

tailoring_preferences:
  default_currency: "GBP"
  max_page_count: 1
  strict_anti_hallucination: true
"""
    with open("config.yaml", "w") as f:
        f.write(config_content)
    print("✅ Created config.yaml")

    # 6. Copy chosen template to CV_Base.tex with candidate name replacement
    if os.path.exists(chosen_template):
        with open(chosen_template, "r") as f:
            tex_content = f.read()

        # Replace header details
        tex_content = tex_content.replace("ALEX TAYLOR", f"{first_name.upper()} {last_name.upper()}")
        tex_content = tex_content.replace("alex.taylor@example.com", email)
        tex_content = tex_content.replace("+44 7123 456789", phone)
        tex_content = tex_content.replace("London, UK", location)
        
        with open("CV_Base.tex", "w") as f:
            f.write(tex_content)
        print(f"✅ Created CV_Base.tex (from {chosen_template})")

    # 7. Configure Overleaf git remote if provided
    if use_overleaf and overleaf_url:
        os.system(f"git remote add overleaf '{overleaf_url}' 2>/dev/null || git remote set-url overleaf '{overleaf_url}'")
        print(f"✅ Added git remote 'overleaf' -> {overleaf_url}")

    print("\n" + "=" * 70)
    print(" 🎉 SETUP COMPLETE!")
    print("=" * 70)
    print("Next steps:")
    print("1. Review and refine your work history in `CV_Base.tex`.")
    print("2. Add your verified metrics in `.agents/rules/candidate-profile.md`.")
    print("3. Drop any job description file into `JD/`.")
    print("4. Tell your AI assistant: 'new JD'!")
    print("=" * 70 + "\n")

if __name__ == "__main__":
    main()

